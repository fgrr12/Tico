#!/usr/bin/env bash
# Writes Signing.xcconfig (gitignored) from the first "Apple
# Development" identity in the login keychain. A stable identity keeps macOS
# the Apple Events grant across rebuilds. Override with IDENTITY="…" TEAM="…".
set -euo pipefail
OUT="$(cd "$(dirname "$0")/.." && pwd)/apps/macos/Signing.xcconfig"
[ -f "$OUT" ] && [ -z "${FORCE:-}" ] && exit 0

IDENTITY="${IDENTITY:-$(security find-identity -v -p codesigning | sed -n 's/.*"\(Apple Development: .*\)"/\1/p' | head -1)}"
if [ -z "$IDENTITY" ]; then
  echo "No Apple Development identity found; using ad-hoc signing (Apple Events must be re-granted after each build)." >&2
  printf 'CODE_SIGN_STYLE = Manual\nCODE_SIGN_IDENTITY = -\n' > "$OUT"
  exit 0
fi
TEAM="${TEAM:-$(security find-certificate -c "$IDENTITY" -p | openssl x509 -noout -subject | sed -n 's/.*OU *= *\([A-Z0-9]*\).*/\1/p')}"
cat > "$OUT" <<XC
// Generated by scripts/setup-signing.sh — local only, not committed.
CODE_SIGN_STYLE = Manual
CODE_SIGN_IDENTITY = $IDENTITY
DEVELOPMENT_TEAM = $TEAM
PROVISIONING_PROFILE_SPECIFIER =
XC
echo "✓ signing: $IDENTITY (team $TEAM) → $OUT"
